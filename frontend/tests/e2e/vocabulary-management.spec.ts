  await page.getByRole('menuitem', { name: 'Clear entire Vocabulary Library' }).click();
  const clear = page.getByRole('button', { name: 'Clear my vocabulary' });
  await expect(clear).toBeDisabled();
  await page.getByRole('button', { name: 'Back up & inspect my library' }).click();
  await expect(page.getByText('Backup status: Created and verified in private storage')).toBeVisible();
  await expect(clear).toBeDisabled();
